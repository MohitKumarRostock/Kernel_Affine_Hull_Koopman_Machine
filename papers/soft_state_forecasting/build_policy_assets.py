#!/usr/bin/env python3
"""Build policy-augmentation manuscript displays from pinned published records.

No fitting, candidate selection, or forecast scoring is performed. The input
bundle includes the exact published tables, source manifests and audit receipts.
Statistical endpoints and natural aggregates are recomputed from their saved
repetition/per-series summaries, with all input/output hashes retained.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import re
import statistics
from pathlib import Path

from scipy.stats import t

SOURCE_COMMIT = "b1915813e98a59572a4bbb800adc2bd1f3fccc1b"
RESULTS_COMMIT = "b59410407a7cd34155aa1955fe0c801f62381364"


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def close(a, b, label):
    if not math.isclose(float(a), float(b), rel_tol=1e-10, abs_tol=1e-12):
        raise ValueError(f"Mismatch {label}: {a} != {b}")


def main():
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--evidence-root", type=Path,
                    default=here / "evidence" / "policy_augmentation")
    ap.add_argument("--output-root", type=Path,
                    default=here / "generated" / "policy_augmentation")
    args = ap.parse_args()
    base, out = args.evidence_root.resolve(), args.output_root.resolve()
    out.mkdir(parents=True, exist_ok=True)
    inputs, outputs, checks = {}, {}, []

    def raw(rel):
        p = base / rel
        data = p.read_bytes()
        inputs[rel] = {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
        return data

    def js(rel):
        return json.loads(raw(rel))

    def rows(rel):
        return list(csv.DictReader(raw(rel).decode().splitlines()))

    def write(name, content):
        p = out / name
        p.write_text(content, encoding="utf-8")
        outputs[name] = {"bytes": p.stat().st_size, "sha256": sha256(p)}

    def table(name, spec, headers, body):
        lines = [r"% Generated by build_policy_assets.py; do not edit.",
                 r"\begin{tabular}{@{}" + spec + r"@{}}", r"\toprule",
                 " & ".join(headers) + r" \\", r"\midrule"]
        lines += [" & ".join(map(str, row)) + r" \\" for row in body]
        lines += [r"\bottomrule", r"\end{tabular}", ""]
        write(name + ".tex", "\n".join(lines))

    syn = "extensions/policy_augmentation_20261101/"
    nat = "extensions/policy_augmentation_natural_20261101/"
    ss = js(syn + "analysis/analysis_summary.json")
    ns = js(nat + "analysis/analysis_summary.json")
    sc = js(syn + "config.json")
    nc = js(nat + "config.json")
    pri = rows(syn + "analysis/primary_results.csv")
    paired = rows(syn + "analysis/primary_paired_repetitions.csv")
    panel = rows(syn + "analysis/panel_summary.csv")
    sel = rows(syn + "analysis/selection_by_task.csv")
    freq = rows(syn + "analysis/selection_frequencies.csv")
    resources = rows(syn + "analysis/resource_summary.csv")
    n_ag = rows(nat + "analysis/aggregates.csv")
    n_task = rows(nat + "analysis/task_methods.csv")
    n_metrics = js(nat + "analysis/report_metrics.json")
    roster = js(nat + "roster.json")
    syn_results = raw(syn + "RESULTS.md").decode()
    remote = js("REMOTE_BLOBS.json")

    # Every used archived record must match its exact immutable Git object.
    bypath = {x["path"]: x for x in remote}
    for rel, meta in list(inputs.items()):
        if rel not in bypath:
            if rel != "REMOTE_BLOBS.json":
                raise ValueError(f"No pinned Git identity: {rel}")
            continue
        data = (base / rel).read_bytes()
        blob = hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()
        if blob != bypath[rel]["sha"]:
            raise ValueError(f"Published Git blob mismatch: {rel}")
        meta["git_blob_sha1"] = blob
        meta["results_commit"] = RESULTS_COMMIT

    # Released analysis summaries independently pin the numerical input tables.
    for prefix, hashes in [(syn, {k: v["sha256"] for k, v in ss["tables"].items()}),
                           (nat, ns["files"])]:
        for name, expected in hashes.items():
            rel = prefix + "analysis/" + name
            if rel in inputs:
                assert inputs[rel]["sha256"] == expected, rel
                checks.append({"check": "released_table_hash", "path": rel, "passed": True})

    assert sc["repetitions"] == 24 and sc["task_count"] == 192
    assert sc["native_cap_order"] == nc["caps"] == [1, 2, 4, 8, 12]
    assert sc["analysis"]["primary_family_size"] == 4
    assert [len(sc["policy_orders"][k]) for k in ["P0", "P1", "P0plus"]] == [10, 11, 11]
    assert [len(nc["policy_orders"][k]) for k in ["P0", "P1", "P0plus"]] == [11, 12, 12]

    stat_results = []
    critical = float(t.ppf(1 - .05 / 4, 23))
    for r in pri:
        subset = [x for x in paired if x["contrast_id"] == r["contrast_id"]]
        assert len(subset) == 24 and len({x["repetition"] for x in subset}) == 24
        a = float(r["comparator_factor"])
        diff = [float(x["candidate_smse"]) - a * float(x["comparator_smse"]) for x in subset]
        cm = statistics.mean(float(x["candidate_smse"]) for x in subset)
        rm = statistics.mean(float(x["comparator_smse"]) for x in subset)
        upper = statistics.mean(diff) + critical * statistics.stdev(diff) / math.sqrt(24)
        gain = 100 * (1 - cm / rm)
        for key, value in [("candidate_mean_smse", cm), ("comparator_mean_smse", rm),
                           ("critical_t", critical), ("simultaneous_one_sided_upper", upper),
                           ("point_relative_gain_percent", gain)]:
            close(r[key], value, r["contrast_id"] + "/" + key)
        assert (upper < 0) == (r["criterion_established"] == "True")
        stat_results.append({"contrast": r["contrast_id"], "upper": upper,
                             "gain_percent": gain, "established": upper < 0})
    assert sum(x["established"] for x in stat_results) == 2
    checks.append({"check": "all_four_prespecified_bounds_from_24_paired_repetitions",
                   "passed": True, "results": stat_results})

    # Reaggregate all three natural policies and each standalone mechanism head.
    natural_checks = []
    wanted = ["policy__calibrated__" + x for x in ["P0", "P1", "P0plus"]]
    wanted += ["residual__calibrated__" + x for x in ["shared_bias", "insample_kahm", "insample_rbf"]]
    for method in wanted:
        for metric in ["SMSE", "seasonal_MASE", "frequency_MASE"]:
            frequency_means = []
            for f in ["Weekly", "Hourly"]:
                values = [float(x[metric]) for x in n_task if x["method_key"] == method and x["frequency"] == f]
                assert len(values) == 24
                mu = statistics.mean(values)
                expected = next(x for x in n_ag if x["method_key"] == method and x["panel"] == f)
                close(mu, expected[metric], f + "/" + method + "/" + metric)
                frequency_means.append(mu)
            mu = statistics.mean(frequency_means)
            expected = next(x for x in n_ag if x["method_key"] == method and x["panel"] == "Overall")
            close(mu, expected[metric], "Overall/" + method + "/" + metric)
            natural_checks.append({"method": method, "metric": metric, "mean": mu})
    checks.append({"check": "natural_means_from_all_48_per_series_records", "passed": True,
                   "results": natural_checks})

    def smean(method, p="nonlinear"):
        return float(next(x for x in panel if x["forecast_key"] == method and x["panel"] == p)["mean_smse"])

    def nrow(method, p="Overall"):
        return next(x for x in n_ag if x["method_key"] == method and x["panel"] == p)

    def gain(c, r):
        return 100 * (1 - c / r)

    p0, p1, pp = [smean("policy__calibrated__" + k) for k in ["P0", "P1", "P0plus"]]
    kh, bias, rb = [smean("crossfit__calibrated__" + k) for k in ["insample_kahm", "shared_bias", "insample_rbf"]]
    np0, np1, npp = [float(nrow("policy__calibrated__" + k)["SMSE"]) for k in ["P0", "P1", "P0plus"]]
    active = [x for x in sel if x["policy"] == "P1" and x["selected_identity"] == "crossfit__insample_kahm"]
    assert len(active) == 44
    nactive = n_metrics["selected_KAHM_series_details"]
    assert {x["task_id"] for x in nactive} == {"weekly__W160", "weekly__W196", "hourly__H368"}

    macros = {
        "PAGainPZero": f"{gain(p1,p0):.2f}", "PAGainExtra": f"{gain(p1,pp):.2f}",
        "PANaturalPenalty": f"{-gain(np1,np0):.2f}", "PANaturalGainExtra": f"{gain(np1,npp):.2f}",
        "PAMechanismBiasGain": f"{gain(kh,bias):.2f}", "PAMechanismRBFGain": f"{gain(kh,rb):.2f}",
        "PAStandalonePolicyPenalty": f"{-gain(kh,p0):.2f}",
        "PASyntheticSelections": "44", "PANaturalSelections": "3", "PARepetitions": "24",
        "PATasks": "192", "PANaturalSeries": "48",
        "PANaturalBiasGain": f"{n_metrics['standalone_KAHM_shared_baseline_descriptive']['KAHM_gain_vs_bias_percent']:.2f}",
        "PANaturalRBFGain": f"{n_metrics['standalone_KAHM_shared_baseline_descriptive']['KAHM_gain_vs_ISRBF_percent']:.2f}",
    }
    write("numbers.tex", "% Generated from pinned published records.\n" + "\n".join(
        "\\newcommand{\\" + k + "}{" + v + "}" for k, v in macros.items()) + "\n")

    labels = {"P0": r"$P_0$", "P1": r"$P_1$", "P0plus": r"$P_0^+$"}
    table("synthetic_policy_table", "lrr", ["Policy", "Nonlinear SMSE", "Linear SMSE"], [
        [labels[k], f"{smean('policy__calibrated__'+k):.8f}", f"{smean('policy__calibrated__'+k,'linear'):.8f}"]
        for k in labels])
    table("synthetic_primary_table", "llrrrl", ["Panel", "Comparator", "Margin", r"Gain (\%)", "Upper bound", "Established"], [
        [r["panel"].capitalize(), labels[r["comparator"]], r"3\%" if r["panel"] == "nonlinear" else r"5\%",
         f"{float(r['point_relative_gain_percent']):+.4f}", f"{float(r['simultaneous_one_sided_upper']):+.6f}",
         "Yes" if r["criterion_established"] == "True" else "No"] for r in pri])

    laws = [("linear_ar", "Linear AR"), ("nonlinear_ar", "Nonlinear AR"), ("vanderpol", "Van der Pol"), ("duffing", "Duffing")]
    cond = []
    for law, label in laws:
        for noise in [0., .1]:
            means = []
            for k in labels:
                group = [x for x in sel if x["law"] == law and float(x["noise_level"]) == noise and x["policy"] == k]
                assert len(group) == 24
                means.append(statistics.mean(float(x["D_smse"]) for x in group))
            count = sum(x["law"] == law and float(x["noise_level"]) == noise for x in active)
            cond.append([label, f"{noise:.1f}", *[f"{x:.6f}" for x in means], f"{gain(means[1],means[0]):+.2f}", f"{count}/24"])
    table("synthetic_condition_table", "lrrrrrr", ["Law", "Noise", r"$P_0$", r"$P_1$", r"$P_0^+$", r"Gain (\%)", "KAHM chosen"], cond)

    table("natural_policy_table", "lrrrrr", ["Policy", r"\shortstack{Weekly\\SMSE}", r"\shortstack{Hourly\\SMSE}",
          r"\shortstack{Overall\\SMSE}", r"\shortstack{Frequency\\MASE}", r"\shortstack{Seasonal\\MASE}"], [
        [labels[k], *[f"{float(nrow('policy__calibrated__'+k,p)['SMSE']):.6f}" for p in ["Weekly", "Hourly", "Overall"]],
         f"{float(nrow('policy__calibrated__'+k)['frequency_MASE']):.6f}", f"{float(nrow('policy__calibrated__'+k)['seasonal_MASE']):.6f}"]
        for k in labels])
    scaler = {"standard": "Standard", "minmax": "Min--max", "tanh_z_1": "Tanh"}
    table("natural_selected_table", "lrlrrr", ["Series", "Cap", "Transform", r"$P_0$ SMSE", r"$P_1$ SMSE", r"Gain (\%)"], [
        [x["task_id"].split("__")[1], x["requested_cap"], scaler[x["scaler"]],
         f"{x['P0_SMSE']:.6f}", f"{x['P1_SMSE']:.6f}", f"{x['KAHM_gain_vs_P0_percent']:+.2f}"] for x in nactive])

    # Synthetic fit-metadata summaries are transcribed from the pinned release,
    # not represented as an independent replay of unavailable full fitted states.
    m = re.search(r"\*\*All B-selected KAHM fits:\*\* 192 tasks\. Requested-cap counts: (.*?)\. Scaler counts: (.*?)\.", syn_results)
    if not m:
        raise ValueError("Pinned synthetic selection summary not found")
    counts = dict((int(k), int(v)) for k,v in re.findall(r"(\d+): (\d+)", m.group(1)))
    scales = dict((k, int(v)) for k,v in re.findall(r"(\w+): (\d+)", m.group(2)))
    nr = n_metrics["correction_selections"]["kahm"]
    assert sum(counts.values()) == sum(scales.values()) == 192
    table("selection_table", "lrrrrrrrr", ["KAHM cohort", "1", "2", "4", "8", "12", "Standard", "Min--max", "Tanh"], [
        ["Simulation (192)", *[counts[c] for c in [1,2,4,8,12]], *[scales[k] for k in ["standard", "minmax", "tanh_z_1"]]],
        ["Natural (48)", *[nr["requested_cap"][str(c)] for c in [1,2,4,8,12]], *[nr["scaler"][k] for k in ["standard", "minmax", "tanh_z_1"]]],
    ])

    ordered = [roster["frequencies"][f]["selected"] for f in ["Weekly", "Hourly"]]
    assert all(len(a) == 24 for a in ordered)
    table("natural_roster_table", "lrrlrr", ["Weekly ID", r"$N$", "A rows", "Hourly ID", r"$N$", "A rows"], [
        [w["series_id"], w["n_observations"], w["A_rows"], h["series_id"], h["n_observations"], h["A_rows"]]
        for w,h in zip(*ordered)])

    rs = {r["resource"]: r for r in resources}
    rn = ns["resources"]
    table("resources_table", "lrr", ["Whole-suite measurement", "Simulation", "Natural"], [
        ["Fit-worker wall seconds, summed", f"{float(rs['total_wall_seconds']['sum']):,.2f}", f"{rn['fit_worker_wall_seconds_sum']:,.2f}"],
        ["Fit-worker CPU seconds, summed", f"{float(rs['total_cpu_seconds']['sum']):,.2f}", f"{rn['fit_worker_cpu_seconds_sum']:,.2f}"],
        ["Largest worker RSS (MiB)", f"{float(rs['peak_rss_KiB']['maximum'])/1024:,.2f}", f"{rn['peak_worker_rss_MiB']:,.2f}"],
        ["Complete compressed fitted states (MiB)", f"{float(rs['state_gzip_bytes']['sum'])/2**20:,.2f}", f"{rn['complete_state_gzip_bytes']/2**20:,.2f}"],
    ])

    metrics = {"source_commit": SOURCE_COMMIT, "results_commit": RESULTS_COMMIT,
               "macros": macros, "primary": pri, "independent_recomputation": checks,
               "synthetic_conditions": cond, "natural_active_series": nactive,
               "scope": "Reporting-only reconstruction from published tables; no model refit or raw forecast replay.",
               "selection_summary_scope": "Synthetic cap/scaler counts read from pinned RESULTS.md; natural counts read from report_metrics.json. Full fitted-state replay not performed."}
    write("metrics.json", json.dumps(metrics, indent=2) + "\n")
    manifest = {"schema": "kahm-policy-augmentation-manuscript-assets-v1", "source_commit": SOURCE_COMMIT,
                "results_commit": RESULTS_COMMIT, "builder_sha256": sha256(Path(__file__)),
                "inputs": inputs, "outputs": outputs, "scope": metrics["scope"]}
    (out / "asset_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"status": "passed", "inputs": len(inputs), "outputs": len(outputs),
                      "primary_criteria_established": 2, "primary_criteria_total": 4,
                      "output_directory": str(out)}, indent=2))


if __name__ == "__main__":
    main()
