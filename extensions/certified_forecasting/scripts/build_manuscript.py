#!/usr/bin/env python3
"""Build the complete main paper and its reproducible experimental supplement.

The detailed study sources are retained unchanged. Supplement-only copies
expand their table inputs and qualify references to the main paper. Every
proof of a main-paper result stays in main.pdf.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import subprocess


SUPPLEMENT_SOURCES = (
    ("01_kahm", "sections/supplement_kahm_implementation.tex"),
    ("02_witness", "sections/witness_experiments.tex"),
    ("03_decisions", "sections/archive/decision_value_detailed.tex"),
    ("04_forecasting", "sections/experiments.tex"),
    ("05_oscillators", "sections/oscillators.tex"),
    ("06_budgets", "sections/sensitivity.tex"),
    ("07_pendigits", "sections/real_data.tex"),
    ("08_scaling", "sections/input_scaling.tex"),
    ("09_matched", "sections/matched_geometry.tex"),
    ("10_speech", "sections/speech_forecasting.tex"),
    ("11_protocols", "sections/protocols.tex"),
)


def expand_inputs(paper: Path, relative: str, stack=()) -> str:
    path = (paper / relative).resolve()
    if path.suffix != ".tex":
        path = path.with_suffix(".tex")
    if not path.is_relative_to(paper.resolve()) or path in stack:
        raise ValueError(f"Unsafe or cyclic TeX input: {relative}")
    text = path.read_text()
    return re.sub(
        r"\\input\{([^}]+)\}",
        lambda match: expand_inputs(paper, match[1], stack + (path,)),
        text,
    )


def prepare_supplement(paper: Path) -> None:
    expanded = [(name, source, expand_inputs(paper, source))
                for name, source in SUPPLEMENT_SOURCES]
    labels = set(re.findall(r"\\label\{([^}]+)\}",
                            "\n".join(text for _, _, text in expanded)))
    destination = paper / "supplement_sections"
    destination.mkdir(exist_ok=True)
    for name, source, text in expanded:
        def qualify(match):
            command, label = match.groups()
            target = label if label in labels else "main-" + label
            return "\\" + command + "{" + target + "}"
        text = re.sub(r"\\(ref|eqref|pageref)\{([^}]+)\}", qualify, text)
        header = (f"% Generated by scripts/build_manuscript.py from {source}.\n"
                  "% Edit the source, then regenerate; all outcomes are retained.\n")
        (destination / f"{name}.tex").write_text(header + text)


def compile_tex(paper: Path, stem: str) -> None:
    process = subprocess.run(
        ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", f"{stem}.tex"],
        cwd=paper, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
    )
    (paper / f"{stem}.build.txt").write_text(process.stdout)
    if process.returncode:
        print(process.stdout[-16000:])
        raise SystemExit(process.returncode)
    log = (paper / f"{stem}.log").read_text(errors="replace")
    issues = [line for line in log.splitlines()
              if ("undefined" in line and ("Reference" in line or "Citation" in line))
              or "multiply defined" in line or "Overfull" in line]
    for line in issues:
        print(f"{stem}: {line}")
    if issues:
        raise SystemExit(f"Inspect unresolved references or layout in {stem}.log")
    summary = next((line for line in log.splitlines() if "Output written on" in line),
                   f"{stem}.pdf is up to date")
    print(summary)


def main() -> None:
    here = Path(__file__).resolve()
    default = here.parent if (here.parent / "main.tex").exists() else here.parents[1] / "paper"
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paper", type=Path, default=default)
    parser.add_argument("--prepare-only", action="store_true",
                        help="Regenerate supplement sources without invoking LaTeX")
    args = parser.parse_args()
    paper = args.paper.resolve()
    prepare_supplement(paper)
    if not args.prepare_only:
        compile_tex(paper, "main")
        compile_tex(paper, "supplement")


if __name__ == "__main__":
    main()
