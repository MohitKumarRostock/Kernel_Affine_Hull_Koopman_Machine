"""Reaggregate every paired scaling arm from the retained recording-group losses."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

FAMILIES = (("kahm", "KAHM"), ("rbf", "RBF"), ("affine", "Affine hull"))
MODES = ("standard", "raw", "minmax", "minmax_clip")


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def generate(results):
    loss = pd.read_csv(results / "group_losses.csv.gz", dtype={"group": str}, float_precision="round_trip")
    records = json.loads((results / "results.json").read_text())["results"]
    selected = loss.groupby(["seed", "family", "scaling"], sort=True).mse.mean().reset_index()
    details = pd.DataFrame([{k: r[k] for k in ("seed", "family", "scaling", "candidate", "history", "features")} for r in records])
    selected = selected.merge(details, on=["seed", "family", "scaling"], validate="one_to_one")
    if len(selected) != 36 or len(loss) != 26460:
        raise AssertionError("Unexpected study accounting")
    summary = selected.groupby(["family", "scaling"], sort=True).mse.agg(["mean", "std"])
    selected.to_csv(results / "all_horizon_selected.csv", index=False)
    summary.to_csv(results / "all_horizon_summary.csv")
    comparisons, rows = [], []
    for family, name in FAMILIES:
        pivot = selected[selected.family == family].pivot(index="seed", columns="scaling", values="mse")
        relative = 100 * (pivot["minmax"].mean() / pivot["standard"].mean() - 1)
        favorable = int((pivot["minmax"] < pivot["standard"]).sum())
        per_seed = (100 * (pivot["minmax"] / pivot["standard"] - 1)).to_dict()
        comparisons.append({"family": family, "relative_minmax_vs_standard_percent": relative,
            "favorable_fits": favorable, "n_fits": len(pivot), "per_seed_relative_percent": per_seed})
        entries = [name]
        for mode in MODES:
            r = summary.loc[(family, mode)]
            entries.append(f"{1000*r['mean']:.3f} ({1000*r['std']:.3f})")
        entries += [f"${relative:+.2f}$", f"{favorable}/3"]
        rows.append(" & ".join(entries) + r" \\")
    table = r"""% Generated by experiments/speech_scaling/make_assets.py from retained group losses.
\begin{table}[t]
\centering
\small
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{lrrrrrr}
\toprule
& Standard & Raw & Min--max & Clipped & $\Delta\%$ & Fits \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\caption{Descriptive speech scaling comparison on the same 245 test groups.
Entries are all-horizon MSE means (sample standard deviations across three fits),
multiplied by $10^3$. Each fit averages the three horizon MSEs with equal weight.
All model choices within an arm use validation data. $\Delta\%$ compares the
min--max and standardized means; negative values favor min--max. ``Fits'' counts
the paired fits with lower min--max MSE. The clipped arm shares training extrema
and clips held-out inputs to $[-1,1]$. This reused-cohort follow-up supplies no
new confidence or certification claim.}
\label{tab:speech-scaling}
\end{table}
"""
    (results / "speech_scaling.tex").write_text(table)
    (results / "all_horizon_comparisons.json").write_text(json.dumps(comparisons, indent=2) + "\n")
    outputs = ["all_horizon_selected.csv", "all_horizon_summary.csv", "all_horizon_comparisons.json", "speech_scaling.tex"]
    manifest = {"generator_sha256": digest(__file__), "loss_sha256": digest(results / "group_losses.csv.gz"),
                "results_sha256": digest(results / "results.json"),
                "outputs": {name: digest(results / name) for name in outputs}}
    (results / "asset_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(comparisons, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", type=Path, required=True)
    generate(parser.parse_args().results)
