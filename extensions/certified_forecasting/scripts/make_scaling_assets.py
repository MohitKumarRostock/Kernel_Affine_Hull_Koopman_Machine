"""Generate manuscript input-scaling tables from the complete audited analyses.

This script performs no fitting or selection. The input CSVs retain the frozen
validation-selected outcomes, every fitting seed, and all preprocessing arms.
It never writes any original experiment table or figure.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TASKS = (
    ("main_v1", "harmonic", "Harmonic"),
    ("main_v1", "quasiperiodic", "Quasiperiodic"),
    ("main_v1", "nonlinear_ar", "Nonlinear AR"),
    ("main_v1", "logistic", "Logistic"),
    ("oscillators_v1", "vanderpol", "Van der Pol"),
    ("oscillators_v1", "duffing", "Duffing"),
    ("pendigits_v1", "pendigits", "PenDigits"),
)


def read_csv(path):
    with Path(path).open(newline="") as stream:
        return list(csv.DictReader(stream))


def one(rows, **keys):
    found = [row for row in rows if all(row[key] == str(value) for key, value in keys.items())]
    if len(found) != 1:
        raise ValueError(f"Expected exactly one row for {keys}; found {len(found)}")
    return found[0]


def comparison(rows, campaign, system, mode="minmax", family="kahm_nested"):
    return one(rows, campaign=campaign, system=system, mode=mode, family=family, horizon="all")


def signed_percent(row):
    return f"{float(row['relative_mse_change_percent']):+.2f}"


def wins(row):
    return row["n_seeds_improved"] + "/" + row["n_fitting_seeds"]


def table_start(columns, size=r"\small", spacing="3pt"):
    return [r"\begin{table}[tbp]", r"\centering" + size,
            r"\setlength{\tabcolsep}{" + spacing + "}",
            r"\begin{tabular}{" + columns + "}", r"\toprule"]


def table_end(caption, label):
    return [r"\bottomrule", r"\end{tabular}", r"\caption{" + caption + "}",
            r"\label{" + label + "}", r"\end{table}"]


def write_table(directory, name, lines):
    (directory / name).write_text("% Generated by scripts/make_scaling_assets.py; do not edit numeric cells.\n"
                                  + "\n".join(lines) + "\n")


def create_assets(analysis, confirmation, output):
    output.mkdir(parents=True, exist_ok=True)
    paths = {
        "original_comparisons": analysis / "taskwise_comparison.csv",
        "confirmation_comparisons": confirmation / "taskwise_comparison.csv",
        "original_horizons": analysis / "horizon_summary.csv",
        "confirmation_horizons": confirmation / "horizon_summary.csv",
    }
    original = read_csv(paths["original_comparisons"])
    fresh = read_csv(paths["confirmation_comparisons"])
    old_horizons = read_csv(paths["original_horizons"])
    new_horizons = read_csv(paths["confirmation_horizons"])
    for root in (analysis, confirmation):
        audit = json.loads((root / "audit.json").read_text())
        if any(row["status"] != "exact" for row in audit["non_kahm_invariance"].values()):
            raise ValueError(f"Non-KAHM control audit is not exact in {root}")
    audit = json.loads((analysis / "audit.json").read_text())
    if any(row["status"] != "exact" for row in audit["baseline_replay"].values()):
        raise ValueError("Original baseline replay audit must be exact")

    lines = table_start("lrrrrrrrr", spacing="2.5pt")
    lines += [r"& \multicolumn{4}{c}{Original fitting seeds} & \multicolumn{4}{c}{New fitting seeds}\\",
              r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}",
              r"Task & Standard & Min--max & $\Delta\%$ & Wins & Standard & Min--max & $\Delta\%$ & Wins\\", r"\midrule"]
    for campaign, system, label in TASKS:
        values = [label]
        for rows in (original, fresh):
            row = comparison(rows, campaign, system)
            values += [f"{float(row['standard_mean_mse']):.6f}", f"{float(row['alternative_mean_mse']):.6f}",
                       signed_percent(row), wins(row)]
        lines.append(" & ".join(values) + r"\\")
    lines += table_end(
        r"Validation-selected retained KAHM predictors: mean test MSE over all three horizons and fitting seeds. "
        r"The primary alternative is training min--max scaling without query clipping. "
        r"$\Delta\%=100(\mathrm{MSE}_{\rm minmax}/\mathrm{MSE}_{\rm standard}-1)$; negative values denote improvement. "
        r"Wins counts fitting repetitions with a smaller all-horizon MSE. Original main tasks have five repetitions; "
        r"original oscillators and PenDigits have three. All new-seed comparisons have three. "
        r"Synthetic confirmation uses new development, calibration, and test episodes. PenDigits confirmation uses new "
        r"training subsamples and the same held-out writer cohort, with coordinate MSE pooled before averaging horizons. "
        r"Original-seed results reuse previously evaluated streams and are descriptive. No average across different task units is taken.", "tab:input-scaling-primary")
    write_table(output, "input_scaling_primary.tex", lines)

    lines = table_start("lrrrr", spacing="5pt")
    lines += [r"& \multicolumn{2}{c}{Original fitting seeds} & \multicolumn{2}{c}{New fitting seeds}\\",
              r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
              r"Task & Clipped min--max & Raw histories & Clipped min--max & Raw histories\\", r"\midrule"]
    for campaign, system, label in TASKS:
        values = [label]
        for rows in (original, fresh):
            values.extend(signed_percent(comparison(rows, campaign, system, mode)) for mode in ("minmax_clip", "raw"))
        lines.append(" & ".join(values) + r"\\")
    lines += table_end(
        r"Diagnostic preprocessing arms, reported as percent change in all-horizon test MSE relative to standardization "
        r"for the retained KAHM family. Negative values denote improvement. Clipped min--max fixes all query inputs "
        r"inside $[-1,1]$; raw histories use the task's existing bounded observations without standardization. "
        r"These test comparisons are descriptive and are not used to choose a preprocessing arm per task. "
        r"New-seed PenDigits results use the same writer cohort.", "tab:input-scaling-diagnostics")
    write_table(output, "input_scaling_diagnostics.tex", lines)

    lines = table_start("lrrrrrr", spacing="5pt")
    lines += [r"& \multicolumn{2}{c}{$\kappa=1$} & \multicolumn{2}{c}{$\kappa=4$} & \multicolumn{2}{c}{$\kappa=16$}\\",
              r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
              r"Task & $\Delta\%$ & Wins & $\Delta\%$ & Wins & $\Delta\%$ & Wins\\", r"\midrule"]
    for _, system, label in TASKS[:4]:
        values = [label]
        for budget in (1, 4, 16):
            row = comparison(original, f"sensitivity_v1_k{budget}", system)
            values += [signed_percent(row), wins(row)]
        lines.append(" & ".join(values) + r"\\")
    lines += table_end(
        r"Scaling comparison within the original coefficient-budget sensitivity protocol: history length 12, "
        r"seeds 2701--2703, and the same data across budgets. Entries are the percent change in mean all-horizon test "
        r"MSE for training min--max scaling relative to standardization, plus the number of improving fitting seeds. "
        r"Every stage is selected by mean validation MSE within its arm and budget. "
        r"Negative values denote improvement. This comparison reuses the original sensitivity streams and is "
        r"descriptive; the six-system confirmation uses new synthetic episodes.", "tab:input-scaling-budget")
    write_table(output, "input_scaling_sensitivity.tex", lines)

    lines = table_start("llrrr", spacing="4pt")
    lines += [r"Fitting seeds & Input preprocessing & $h=1$ & $h=2$ & $h=4$\\", r"\midrule"]
    for seed_label, rows in (("1701--1703", old_horizons), ("4701--4703", new_horizons)):
        for mode, mode_label in (("standard", "Standardization"), ("minmax", "Min--max")):
            values = [seed_label, mode_label]
            for horizon in (1, 2, 4):
                row = one(rows, campaign="pendigits_v1", system="pendigits", mode=mode, family="kahm_nested", horizon=horizon)
                values.append(r"$" + f"{float(row['mean_test_rmse']):.5f}" + r"\pm" +
                              f"{float(row['sd_test_rmse_over_fitting_seeds']):.5f}" + "$")
            lines.append(" & ".join(values) + r"\\")
        if seed_label == "1701--1703":
            lines.append(r"\midrule")
    lines += table_end(
        r"PenDigits retained KAHM forecasting: mean $\pm$ sample SD of coordinate-pooled RMSE over three fitting "
        r"seeds. Coordinate MSE is pooled before taking each seed's square root. All 1,751 eligible digits and "
        r"13 held-out writers are identical across both seed sets and preprocessing arms. The SD measures fitting "
        r"variation on this cohort, not uncertainty across independent test cohorts. A normalized error of 0.01 "
        r"corresponds to 2.5 acquisition pixels.", "tab:input-scaling-pendigits")
    write_table(output, "input_scaling_pendigits.tex", lines)

    lines = table_start("lrrrr", spacing="4pt")
    lines += [r"& \multicolumn{2}{c}{Original fitting seeds} & \multicolumn{2}{c}{New fitting seeds}\\",
              r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
              r"Task & $\overline\Delta\pm s_\Delta$ & $\mathrm{SE}_{\rm ep}$ & $\overline\Delta\pm s_\Delta$ & $\mathrm{SE}_{\rm ep}$\\", r"\midrule"]
    for campaign, system, label in TASKS:
        values = [label]
        for rows in (original, fresh):
            row = comparison(rows, campaign, system)
            values.append("$" + f"{1e3*float(row['mse_difference_alternative_minus_standard']):+.4f}" +
                          r"\pm" + f"{1e3*float(row['paired_mse_difference_sd_over_seeds']):.4f}" + "$")
            values.append("--" if row["conditional_standard_error"] == "" else f"{1e3*float(row['conditional_standard_error']):.4f}")
        lines.append(" & ".join(values) + r"\\")
    lines += table_end(
        r"Two distinct sources of variation for the primary scaling comparison. All numbers are in units of "
        r"$10^{-3}$ MSE for the corresponding task. $\Delta$ is min--max minus standard MSE after averaging "
        r"horizons within a repetition; $s_\Delta$ is its sample SD across complete fitting repetitions. "
        r"$\mathrm{SE}_{\rm ep}$ measures paired test-episode Monte Carlo uncertainty of the mean difference, "
        r"conditional on the fitted, validation-selected models. It does not measure training variability. "
        r"No iid-writer SE is assigned to the fixed PenDigits cohort. "
        r"Original-seed quantities reuse previously evaluated streams and are descriptive. Neither column is a finite-sample certificate of an algorithm-level gain.", "tab:input-scaling-uncertainty")
    write_table(output, "input_scaling_uncertainty.tex", lines)

    macros = []
    for prefix, rows in (("Original", original), ("Confirmation", fresh)):
        for campaign, system, tag in (("main_v1", "harmonic", "Harmonic"), ("main_v1", "quasiperiodic", "Quasi"),
                                     ("main_v1", "nonlinear_ar", "Nonlinear"), ("main_v1", "logistic", "Logistic"),
                                     ("oscillators_v1", "vanderpol", "VDP"), ("oscillators_v1", "duffing", "Duffing"),
                                     ("pendigits_v1", "pendigits", "Pen")):
            row = comparison(rows, campaign, system)
            macros.append(r"\newcommand{\Scaling" + tag + prefix + "Magnitude}{" +
                          f"{abs(float(row['relative_mse_change_percent'])):.2f}" + "}")
        hard = comparison(rows, "pendigits_v1", "pendigits", family="kahm_hard")
        macros.append(r"\newcommand{\ScalingHardPen" + prefix + "Increase}{" +
                      f"{float(hard['relative_mse_change_percent']):.2f}" + "}")
        rollout_wins = sum(float(comparison(rows, campaign, system, family="kahm_koopman")["relative_mse_change_percent"]) < 0
                           for campaign, system, _ in TASKS)
        macros.append(r"\newcommand{\ScalingRollout" + prefix + "ImprovingTasks}{" + str(rollout_wins) + "}")
    for campaign, system, tag in (("oscillators_v1", "vanderpol", "VDP"), ("oscillators_v1", "duffing", "Duffing"),
                                  ("pendigits_v1", "pendigits", "Pen"), ("main_v1", "logistic", "Logistic")):
        rollout = comparison(fresh, campaign, system, family="kahm_koopman")
        macros.append(r"\newcommand{\ScalingRollout" + tag + "ConfirmationMagnitude}{" +
                      f"{abs(float(rollout['relative_mse_change_percent'])):.2f}" + "}")
    write_table(output, "input_scaling_numbers.tex", macros)
    manifest = {
        "generator": "scripts/make_scaling_assets.py",
        "input_files": {name: {"file_name": path.name, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
                        for name, path in paths.items()},
        "numeric_tables": ["input_scaling_primary.tex", "input_scaling_diagnostics.tex", "input_scaling_sensitivity.tex",
                           "input_scaling_pendigits.tex", "input_scaling_uncertainty.tex", "input_scaling_numbers.tex"],
        "selection": "No selection in this generator; use validation-selected rows from audited analyses only.",
    }
    (output / "input_scaling_assets_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--analysis", type=Path, default=ROOT / "results/input_scaling_study/analysis_original")
    parser.add_argument("--confirmation", type=Path, default=ROOT / "results/input_scaling_study/analysis_confirmation")
    parser.add_argument("--output", type=Path, default=ROOT / "paper/tables")
    args = parser.parse_args()
    manifest = create_assets(args.analysis, args.confirmation, args.output)
    print(json.dumps({"output": str(args.output), "tables": manifest["numeric_tables"]}, indent=2))


if __name__ == "__main__":
    main()
