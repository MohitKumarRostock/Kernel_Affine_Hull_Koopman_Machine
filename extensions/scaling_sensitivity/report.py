from .analysis import ROOT, SCALERS, CONTROLLED_FEATURES, CONTROLLED_SYSTEMS


SOURCE_LABELS = {
    "caltrans_bay_area_traffic": "Traffic", "expsmooth_hospital": "Hospital",
    "fred_md_macroeconomics": "FRED-MD", "nn5_atm_cash": "NN5",
    "saugeen_river_flow": "Saugeen", "tourism_competition": "Tourism",
    "uci_electricity_load": "Electricity", "us_births_mosaicdata": "US births",
}
SOURCE_ORDER = {
    "development": ("uci_electricity_load", "nn5_atm_cash", "tourism_competition", "fred_md_macroeconomics"),
    "confirmation": ("caltrans_bay_area_traffic", "expsmooth_hospital", "saugeen_river_flow", "us_births_mosaicdata"),
}
SYSTEM_LABELS = {"nonlinear_ar": "Nonlinear AR", "vanderpol": "Van der Pol", "duffing": "Duffing"}
FEATURE_LABELS = {"raw": "Raw", "affine:local": "Affine local", "locality:local": "Locality local",
                  "kahm:local": "KAHM local", "kahm:scores": "KAHM scores"}
METHOD_LABELS = {"raw_ridge": "Raw ridge", "raw_rbf": "Raw RBF", "raw_affine_rbf": "Raw + affine",
                 "raw_locality_rbf": "Raw + locality", "raw_kahm_rbf": "Raw + KAHM"}
METHOD_ORDER = ("raw_ridge", "raw_rbf", "raw_affine_rbf", "raw_locality_rbf", "raw_kahm_rbf")


def write_tex(path, lines):
    Path(path).write_text("% Generated by scaling_sensitivity/report.py from analysis/summary.json.\n" +
                          "\n".join(lines) + "\n")


def table_open(columns, caption, label, size=r"\small"):
    return [r"\begin{table}[t]", r"\centering", size, r"\begin{tabular}{" + columns + "}",
            r"\toprule"]


def table_close(caption, label):
    return [r"\bottomrule", r"\end{tabular}", r"\caption{" + caption + "}",
            r"\label{" + label + "}", r"\end{table}"]


def _method_scaling_table(summary, phase):
    methods = summary["natural"]["phases"][phase]["methods"]
    caption = ("Geometry-scaling sensitivity on the four formerly reserved natural sources. "
               "Scaled MSE uses the original source hierarchy. Standard arms reproduce the frozen "
               "results; min--max changes geometry only, retains the raw skip, and applies no input clipping. "
               r"Change is $100(\ell_{\mathrm{minmax}}/\ell_{\mathrm{standard}}-1)$; negative favors min--max. "
               "Raw references are fixed. All new comparisons are post-hoc sensitivity.")
    if phase == "development":
        caption = ("The same fixed sensitivity comparison on the four original development sources. "
                   "Their outcomes remain separate from the formerly reserved sources. Scaled MSE "
                   "uses the original equal-source hierarchy; change is min--max versus standard in percent. "
                   "Raw references are fixed, and no scaler is selected from these test outcomes.")
    label = "tab:scaling-natural" if phase == "confirmation" else "tab:scaling-development"
    lines = table_open("lrrr", caption, label)
    lines.extend([r"Method & Standard MSE & Min--max MSE & Change (\%) \\", r"\midrule"])
    for method in METHOD_ORDER:
        if method in ("raw_ridge", "raw_rbf"):
            value = methods[method]["scaled_mse"]
            lines.append(f"{METHOD_LABELS[method]} & {value:.4f} & {value:.4f} & fixed " + r"\\")
        else:
            before = methods[method + "__standard"]["scaled_mse"]
            after = methods[method + "__minmax"]["scaled_mse"]
            delta = 100 * (after / before - 1)
            lines.append(f"{METHOD_LABELS[method]} & {before:.4f} & {after:.4f} & {delta:+.2f} " + r"\\")
    return lines + table_close(caption, label)


def _natural_cost_table(summary):
    methods = summary["natural"]["phases"]["confirmation"]["methods"]
    caption = ("Contemporaneous, source-balanced warm method times (seconds) on the four formerly reserved sources. "
               "Each method independently performs its alpha search, selected refit, prediction, serialization, "
               "and cleanup. These totals exclude reused data preparation, current input loading, process startup, "
               "and additional sensitivity audits. Launch-to-result and audit elapsed times are recorded separately; "
               "the inherited partial import timer is not a complete cold-start measure. Every timing, including "
               "outliers, is retained. These single-execution observations are implementation-specific and should "
               "not be divided by timings from the earlier execution.")
    label = "tab:scaling-costs"
    lines = table_open("lrrrrrr", caption, label, r"\scriptsize")
    lines[0] = r"\begin{table}[!htbp]"
    lines.extend([r"Method / geometry scaler & Search & Cleanup & Refit & Forecast & Serialize & Total \\", r"\midrule"])
    for method in METHOD_ORDER:
        for scaling in (("fixed",) if method in ("raw_ridge", "raw_rbf") else SCALERS):
            key = method if scaling == "fixed" else method + "__" + scaling
            values = methods[key]
            name = METHOD_LABELS[method] + ("" if scaling == "fixed" else " / " + ("std." if scaling == "standard" else "min--max"))
            fields = ("search_seconds", "selection_overhead_seconds", "refit_seconds", "forecast_seconds",
                      "serialization_seconds", "cost_seconds")
            lines.append(name + " & " + " & ".join(f"{values[field]:.4f}" for field in fields) + r" \\")
    return lines + table_close(caption, label)


def _natural_source_table(summary):
    caption = ("Source-level scaling sensitivity. $K_s$ and $K_m$ denote raw + KAHM with standard and min--max "
               "geometry; $R$, $A_m$, and $L_m$ denote raw RBF, raw + min--max affine, and raw + min--max locality. "
               r"Entries are original-hierarchy scaled MSE; $\Delta\% = 100(K_m/K_s-1)$. Original role labels "
               "identify the historical design, while every newly computed comparison is post-hoc.")
    label = "tab:scaling-sources"
    lines = table_open("lrrrrrr", caption, label, r"\scriptsize")
    lines.extend([r"Source & $K_s$ & $K_m$ & $\Delta\%$ & $R$ & $A_m$ & $L_m$ \\", r"\midrule"])
    for phase, title in (("development", "Original development sources"), ("confirmation", "Formerly reserved sources")):
        lines.append(r"\multicolumn{7}{l}{\emph{" + title + r"}} \\")
        sources = summary["natural"]["phases"][phase]["by_source"]
        for family in SOURCE_ORDER[phase]:
            values = sources[family]
            ks, km = values["raw_kahm_rbf__standard"]["scaled_mse"], values["raw_kahm_rbf__minmax"]["scaled_mse"]
            raw, affine, locality = [values[key]["scaled_mse"] for key in
                                     ("raw_rbf", "raw_affine_rbf__minmax", "raw_locality_rbf__minmax")]
            lines.append(f"{SOURCE_LABELS[family]} & {ks:.4f} & {km:.4f} & {100*(km/ks-1):+.2f} & {raw:.4f} & {affine:.4f} & {locality:.4f} " + r"\\")
        if phase == "development":
            lines.append(r"\midrule")
    return lines + table_close(caption, label)


def _natural_all_sources(summary, phase):
    sources = summary["natural"]["phases"][phase]["by_source"]
    families = SOURCE_ORDER[phase]
    label = "tab:scaling-all-sources-" + phase
    caption = ("Every fixed sensitivity method on the " +
               ("original development sources" if phase == "development" else "formerly reserved sources") +
               ". Entries are source-level scaled MSE using the original nested task weights. "
               "The two raw references retain their original standardization.")
    lines = table_open("lrrrr", caption, label)
    lines.extend(["Method / geometry scaler & " + " & ".join(SOURCE_LABELS[f] for f in families) + r" \\", r"\midrule"])
    for method in METHOD_ORDER:
        for scaling in (("fixed",) if method in ("raw_ridge", "raw_rbf") else SCALERS):
            key = method if scaling == "fixed" else method + "__" + scaling
            name = METHOD_LABELS[method] + ("" if scaling == "fixed" else " / " + ("std." if scaling == "standard" else "min--max"))
            lines.append(name + " & " + " & ".join(f"{sources[f][key]['scaled_mse']:.4f}" for f in families) + r" \\")
    return lines + table_close(caption, label)


def _controlled_main(summary):
    caption = ("Controlled geometry-scaling sensitivity on all 24 original complete draws per law and both "
               "landmark counts $M$. Mean MSE is multiplied by $10^3$. Raw inputs remain standardized; "
               "the min--max columns change only the fitted geometry scaler. Locality is the added matched "
               "coordinate control. These paired reused-draw comparisons are descriptive, with full dispersion "
               r"and the score-only representation in Table~\ref{tab:scaling-controlled-all}.")
    label = "tab:scaling-controlled"
    lines = table_open("lrrrrrr", caption, label, r"\scriptsize")
    lines.extend([r"Law & $M$ & Raw & KAHM std. & KAHM min--max & Affine min--max & Locality min--max \\", r"\midrule"])
    for cell in summary["controlled"]["cells"]:
        values = {(row["scaling"], row["feature"]): row["mean_mse"] for row in cell["methods"]}
        fields = (("standard", "raw"), ("standard", "kahm:local"), ("minmax", "kahm:local"),
                  ("minmax", "affine:local"), ("minmax", "locality:local"))
        lines.append(SYSTEM_LABELS[cell["system"]] + f" & {cell['landmarks']} & " +
                     " & ".join(f"{1000*values[field]:.4f}" for field in fields) + r" \\")
    return lines + table_close(caption, label)


def _controlled_all(summary):
    caption = ("Every controlled sensitivity arm, including raw and KAHM scores. Each entry is mean MSE "
               "with between-repetition SD in parentheses, multiplied by $10^3$, over the same 24 complete draws. "
               r"$\Delta$ is paired min--max-minus-standard mean difference; its parentheses contain paired SD. "
               "These are descriptive dispersions on reused draws, not confidence intervals. The raw arms are identical.")
    lines = [r"\begingroup", r"\scriptsize", r"\setlength{\tabcolsep}{4pt}", r"\begin{longtable}{lrlrrr}",
             r"\caption{" + caption + r"}\label{tab:scaling-controlled-all}\\", r"\toprule",
             r"Law & $M$ & Features & Standard (SD) & Min--max (SD) & $\Delta$ (paired SD) \\",
             r"\midrule", r"\endfirsthead", r"\toprule",
             r"Law & $M$ & Features & Standard (SD) & Min--max (SD) & $\Delta$ (paired SD) \\",
             r"\midrule", r"\endhead", r"\bottomrule", r"\endfoot"]
    for cell in summary["controlled"]["cells"]:
        values = {(row["scaling"], row["feature"]): row for row in cell["methods"]}
        for feature in CONTROLLED_FEATURES:
            before, after = values[("standard", feature)], values[("minmax", feature)]
            if feature == "raw":
                delta, delta_sd = 0.0, 0.0
            else:
                contrast = next(row for row in cell["contrasts"]
                                if row["candidate_scaling"] == "minmax" and row["reference_scaling"] == "standard"
                                and row["candidate_feature"] == feature and row["reference_feature"] == feature)
                delta, delta_sd = contrast["mean_difference"], contrast["difference_sd"]
            lines.append(f"{SYSTEM_LABELS[cell['system']]} & {cell['landmarks']} & {FEATURE_LABELS[feature]} & " +
                         f"{1000*before['mean_mse']:.4f} ({1000*before['mse_sd']:.4f}) & " +
                         f"{1000*after['mean_mse']:.4f} ({1000*after['mse_sd']:.4f}) & " +
                         f"{1000*delta:+.4f} ({1000*delta_sd:.4f}) " + r"\\")
        lines.append(r"\addlinespace")
    lines.extend([r"\end{longtable}", r"\endgroup"])
    return lines


def _numbers(summary):
    confirmation = summary["natural"]["phases"]["confirmation"]
    development = summary["natural"]["phases"]["development"]
    methods = confirmation["methods"]
    kstd, kmin = methods["raw_kahm_rbf__standard"], methods["raw_kahm_rbf__minmax"]
    raw, ridge = methods["raw_rbf"], methods["raw_ridge"]
    values = {
        "ScalingNaturalKahmStandardLoss": (kstd["scaled_mse"], ".4f"),
        "ScalingNaturalKahmMinmaxLoss": (kmin["scaled_mse"], ".4f"),
        "ScalingNaturalRawLoss": (raw["scaled_mse"], ".4f"),
        "ScalingNaturalRidgeLoss": (ridge["scaled_mse"], ".4f"),
        "ScalingNaturalKahmChangePercent": (100*(kmin["scaled_mse"]/kstd["scaled_mse"]-1), ".2f"),
        "ScalingNaturalKahmReductionPercent": (100*(1-kmin["scaled_mse"]/kstd["scaled_mse"]), ".2f"),
        "ScalingNaturalKahmVsRawPercent": (100*(kmin["scaled_mse"]/raw["scaled_mse"]-1), ".2f"),
        "ScalingNaturalKahmVsRidgePercent": (100*(kmin["scaled_mse"]/ridge["scaled_mse"]-1), ".2f"),
        "ScalingNaturalKahmStandardTime": (kstd["cost_seconds"], ".4f"),
        "ScalingNaturalKahmMinmaxTime": (kmin["cost_seconds"], ".4f"),
        "ScalingNaturalRawTime": (raw["cost_seconds"], ".4f"),
        "ScalingNaturalRidgeTime": (ridge["cost_seconds"], ".4f"),
        "ScalingNaturalKahmCostRatioRaw": (kmin["cost_seconds"]/raw["cost_seconds"], ".2f"),
        "ScalingNaturalKahmCostRatioStandard": (kmin["cost_seconds"]/kstd["cost_seconds"], ".2f"),
        "ScalingNaturalFamiliesImproved": (confirmation["primary_scaling_contrast"]["candidate_lower_count"], "d"),
        "ScalingDevelopmentKahmStandardLoss": (development["methods"]["raw_kahm_rbf__standard"]["scaled_mse"], ".4f"),
        "ScalingDevelopmentKahmMinmaxLoss": (development["methods"]["raw_kahm_rbf__minmax"]["scaled_mse"], ".4f"),
        "ScalingDevelopmentKahmChangePercent": (development["primary_scaling_contrast"]["relative_change_percent"], ".2f"),
    }
    return [r"\newcommand{" + "\\" + name + "}{" + format(value, formatting) + "}"
            for name, (value, formatting) in values.items()]


def build(summary_path=None, output=None):
    summary_path = Path(summary_path or ROOT / "analysis/summary.json")
    output = Path(output or summary_path.parent / "generated")
    summary = json.loads(summary_path.read_text())
    output.mkdir(parents=True, exist_ok=True)
    products = {
        "natural_main_table.tex": _method_scaling_table(summary, "confirmation"),
        "natural_development_table.tex": _method_scaling_table(summary, "development"),
        "natural_cost_table.tex": _natural_cost_table(summary),
        "natural_source_table.tex": _natural_source_table(summary),
        "natural_all_sources_development.tex": _natural_all_sources(summary, "development"),
        "natural_all_sources_confirmation.tex": _natural_all_sources(summary, "confirmation"),
        "controlled_main_table.tex": _controlled_main(summary),
        "controlled_all_table.tex": _controlled_all(summary),
        "numbers.tex": _numbers(summary),
    }
    for filename, content in products.items():
        write_tex(output / filename, content)
    return {"generated": sorted(products), "output": str(output)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", type=Path, default=ROOT / "analysis/summary.json")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    print(json.dumps(build(args.summary, args.output), indent=2))


if __name__ == "__main__":
    main()
